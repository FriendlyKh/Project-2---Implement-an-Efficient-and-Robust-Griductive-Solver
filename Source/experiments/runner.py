@dataclass
class ExperimentResult:
    """Recorded metrics for a single puzzle evaluation.

    Attributes:
        puzzle_name: Base filename or label of the puzzle.
        grid_size: N (for N×N grid).
        primary_vars: Number of primary character Boolean variables.
        aux_vars: Number of auxiliary variables generated by encodings.
        total_clauses: Total CNF clauses across all generated formulas.
        sat_calls: Number of SAT queries made.
        decisions: Number of branching choices made by DPLL.
        propagations: Number of unit propagations executed.
        backtracks: Number of backtracks performed during search.
        deduction_steps: Number of deduction steps / reveal waves.
        runtime_sec: Total elapsed execution time in seconds.
        solved: True if the puzzle was completely solved, False otherwise.
        status_message: Notes, failure, or timeout reason.
    """

    puzzle_name: str
    grid_size: int
    primary_vars: int = 0
    aux_vars: int = 0
    total_clauses: int = 0
    sat_calls: int = 0
    decisions: int = 0
    propagations: int = 0
    backtracks: int = 0
    deduction_steps: int = 0
    runtime_sec: float = 0.0
    solved: bool = False
    status_message: str = "SUCCESS"

    def to_dict(self) -> Dict[str, Any]:
        """Convert metric record to dictionary."""
        return asdict(self)


